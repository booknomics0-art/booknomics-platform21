let fixed = 0;
let errors = 0;

filesToFix.forEach((book, idx) => {
  try {
    const filepath = path.join(DRAFTS_DIR, book.filename);
    let content = fs.readFileSync(filepath, 'utf8');
    
    const isNewFormat = content.includes('## 📚 SUMMARY');
    const isOldFormat = content.includes('#SUMMARY');
    
    let title, author, category;
    if (isOldFormat) {
      title = (content.match(/^Title:\s*(.+)$/m) || [])[1] || 'यह रचना';
      author = (content.match(/^Author:\s*(.+)$/m) || [])[1] || 'लेखक';
      category = (content.match(/^Category:\s*(.+)$/m) || [])[1] || 'साहित्य';
    } else {
      title = (content.match(/^# (.+)$/m) || [])[1] || 'यह रचना';
      author = (content.match(/^## (.+?) \(/m) || [])[1] || 'लेखक';
      category = (content.match(/श्रेणी.*?:\s*(.+)$/m) || [])[1] || 'साहित्य';
    }
    
    const templateIndex = idx % expansions.length;
    const expansion = expansions[templateIndex](title.trim(), author.trim(), category.trim());
    
    if (isNewFormat) {
      content = content.replace(/## 🎨 STYLE/, expansion + '\n\n---\n\n## 🎨 STYLE');
    } else if (isOldFormat) {
      const summaryMatch = content.match(/(#SUMMARY\n)([\s\S]*?)(?=#\w+|$)/);
      if (summaryMatch) {
        const beforeSummary = content.substring(0, summaryMatch.index + summaryMatch[1].length);
        const summaryContent = summaryMatch[2];
        const afterSummary = content.substring(summaryMatch.index + summaryMatch[0].length);
        content = beforeSummary + summaryContent.trimEnd() + expansion + '\n\n' + afterSummary;
      }
    }
    
    fs.writeFileSync(filepath, content, 'utf8');
    fixed++;
    
    if ((idx + 1) % 20 === 0) {
      console.log(`  ...fixed ${idx + 1}/${filesToFix.length} files`);
    }
  } catch (err) {
    console.log(`❌ Error fixing ${book.filename}: ${err.message}`);
    errors++;
  }
});

console.log(`\n✅ Phase 4 Complete!`);
console.log(`   Fixed: ${fixed} files`);
console.log(`   Errors: ${errors} files`);
