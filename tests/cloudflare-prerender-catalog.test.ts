import { afterEach, describe, expect, it, vi } from "vitest";

afterEach(() => { vi.unstubAllGlobals(); vi.unstubAllEnvs(); vi.resetModules(); });

describe("Cloudflare SEO prerender catalog bridge", () => {
  it("accepts the one-item PostgREST published status array generated by fetchPaged", async () => {
    vi.stubEnv("PRERENDER_CATALOG_API", "https://www.booknomics.com");
    vi.resetModules();
    const requested = vi.fn(async (url: string) => {
      const query = new URL(url).searchParams;
      expect(query.get("status")).toBe("published");
      expect(query.get("view")).toBe("prerender");
      expect(query.get("language")).toBe("en");
      expect(query.get("sort")).toBe("id");
      return Response.json({ data: [{ id: "one", title: "White Fang" }] });
    });
    vi.stubGlobal("fetch", requested);
    const { fetchCloudflarePrerenderBooks } = await import("../scripts/lib/cloudflare-prerender-catalog.mjs");
    const books = await fetchCloudflarePrerenderBooks("books?select=id,title&is_draft=eq.false&status=in.(published)&language=eq.en&order=id.asc&limit=200");
    expect(books).toEqual([{ id: "one", title: "White Fang" }]);
    expect(requested).toHaveBeenCalledTimes(1);
  });

  it("rejects unsupported status expressions before fetching", async () => {
    vi.stubEnv("PRERENDER_CATALOG_API", "https://www.booknomics.com");
    vi.resetModules();
    const requested = vi.fn();
    vi.stubGlobal("fetch", requested);
    const { fetchCloudflarePrerenderBooks } = await import("../scripts/lib/cloudflare-prerender-catalog.mjs");
    await expect(fetchCloudflarePrerenderBooks("books?select=id&is_draft=eq.false&status=in.(draft)&order=id.asc"))
      .rejects.toThrow(/Unsupported prerender statuses/);
    expect(requested).not.toHaveBeenCalled();
  });
});
